BS_TEST(audio_ogg_decode_tone) {
    std::string err;
    auto        s = na::parse_ogg(tom(), &err);
    BS_CHECK(s && s->rate == 22050 && s->channels == 2);
    if (!s) return std::printf("  %s\n", err.c_str()), void();
    BS_CHECK(s->frames() >= 5512 && s->frames() <= 5513);  // 0,25 s (o ffprobe diz 5513)
    double soma = 0;
    int    cruzamentos = 0;
    for (size_t i = 0; i + 2 < s->pcm.size(); i += 2) {  // canal esquerdo
        soma += double(s->pcm[i]) * s->pcm[i];
        cruzamentos += (s->pcm[i] < 0) != (s->pcm[i + 2] < 0);
    }
    const double rms = std::sqrt(soma / double(s->frames()));
    BS_CHECK(rms > 1000);  // um tom de verdade, nao silencio
    BS_CHECK(cruzamentos > 2 * 440 * 0.25 * 0.9 && cruzamentos < 2 * 440 * 0.25 * 1.1);  // ~440 Hz
}

BS_TEST(audio_ogg_rejects_bad_input) {
    std::string err;
    const auto  bom = tom();
    BS_CHECK(!na::parse_ogg(std::vector<uint8_t>(), &err));
    BS_CHECK(!na::parse_ogg(std::vector<uint8_t>{'O', 'g', 'g', 'S', 0, 0, 0}, &err));
    BS_CHECK(!na::parse_ogg(std::vector<uint8_t>(bom.begin(), bom.begin() + 64), &err));  // so o comeco do cabecalho
    auto meio = std::vector<uint8_t>(bom.begin(), bom.begin() + bom.size() / 2);          // truncado: o que der, sem lixo
    auto s    = na::parse_ogg(meio, &err);
    BS_CHECK(!s || s->frames() < 5512);
}

// "fuzz" curto e deterministico: 300 mutacoes (bytes trocados, cortes, repeticoes) do arquivo bom. Cada uma tem que
// voltar (com audio ou erro), sem travar nem sair dos limites; com o ASan isso vale como teste de seguranca.
BS_TEST(audio_ogg_mutations_never_crash) {
    const auto      bom = tom();
    std::mt19937    rng(20261020);
    std::string     err;
    int             validos = 0;
    for (int k = 0; k < 300; ++k) {
        auto b = bom;
        const int tipo = k % 3;
        if (tipo == 0)
            for (int j = 0; j < 1 + int(rng() % 16); ++j) b[rng() % b.size()] = uint8_t(rng());
        else if (tipo == 1)
            b.resize(rng() % b.size());
        else {
            const size_t ini = rng() % b.size(), n = rng() % 512;
            // copia antes: inserir um intervalo do proprio vetor nele e indefinido (revisao Codex 2026-10-20, BAIXA)
            const std::vector<uint8_t> rep(b.begin() + ini, b.begin() + std::min(b.size(), ini + n));
            b.insert(b.begin() + ini, rep.begin(), rep.end());
        }
        auto s = na::parse_ogg(b, &err);
        if (s) {
            ++validos;
            BS_CHECK(s->frames() <= 2 * 5513 && (s->channels == 1 || s->channels == 2));
        }
    }
    std::printf("  300 mutacoes: %d decodificadas (parciais ou intactas), as outras recusadas\n", validos);
}

